#import "Endpoints.h"

// XOR key (chỉ nằm trong binary dạng byte, không lộ URL khi chạy `strings`)
static const unsigned char kXor[7] = { 'D', 'x', '9', '!', 'q', 'W', 'z' };

static const unsigned char kCheckKey[32]  = { 0x2c, 0x0c, 0x4d, 0x51, 0x02, 0x6d, 0x55, 0x6b, 0x1f, 0x5c, 0x55, 0x04, 0x3e, 0x1e, 0x6a, 0x0e, 0x50, 0x51, 0x5e, 0x34, 0x12, 0x21, 0x1b, 0x52, 0x7e, 0x1a, 0x32, 0x03, 0x6a, 0x08, 0x51, 0x51 };
static const unsigned char kResetBind[33] = { 0x2c, 0x0c, 0x4d, 0x51, 0x02, 0x6d, 0x55, 0x6b, 0x1f, 0x5c, 0x55, 0x04, 0x3e, 0x1e, 0x6a, 0x0e, 0x50, 0x51, 0x5e, 0x25, 0x1f, 0x37, 0x1d, 0x4d, 0x7e, 0x13, 0x3e, 0x14, 0x20, 0x56, 0x49, 0x49, 0x01 };
static const unsigned char kGetMod[30]    = { 0x2c, 0x0c, 0x4d, 0x51, 0x02, 0x6d, 0x55, 0x6b, 0x1f, 0x5c, 0x55, 0x04, 0x3e, 0x1e, 0x6a, 0x0e, 0x50, 0x51, 0x5e, 0x30, 0x1f, 0x30, 0x27, 0x54, 0x4e, 0x15, 0x79, 0x0a, 0x2c, 0x08 };

static NSString *decodeURL(const unsigned char *bytes, int len) {
    NSMutableData *d = [NSMutableData dataWithCapacity:len];
    for (int i = 0; i < len; i++) {
        unsigned char c = bytes[i] ^ kXor[i % (int)sizeof(kXor)];
        [d appendBytes:&c length:1];
    }
    return [[NSString alloc] initWithData:d encoding:NSUTF8StringEncoding];
}

NSString *EndpointCheckKey(void)  { return decodeURL(kCheckKey,  (int)sizeof(kCheckKey));  }
NSString *EndpointResetBind(void) { return decodeURL(kResetBind, (int)sizeof(kResetBind)); }
NSString *EndpointGetMod(void)    { return decodeURL(kGetMod,    (int)sizeof(kGetMod));    }
